    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String user_name=jTextField1.getText();
        String password=jPasswordField1.getText();
        if(user_name.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Username!!!");
        }
        else if(password.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Password!!!");
        }
        else
        {
            AdminDBOperation adop=new AdminDBOperation();
            if(adop.isAdminExisted(user_name, password))
            {
                this.dispose();
                AdminOperationFrame aof=new AdminOperationFrame();
                aof.setExtendedState(JFrame.MAXIMIZED_BOTH);
                aof.setVisible(true);
                Dimension d = Toolkit.getDefaultToolkit().getScreenSize();
                aof.setSize(d);
            }
            else
            {
                 JOptionPane.showMessageDialog(null, "Invalid Credential \n Please Try Again!!!");
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

