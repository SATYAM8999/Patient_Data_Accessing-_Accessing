    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String username=jTextField5.getText();
        String password=jPasswordField1.getText();
        String conf_password=jPasswordField2.getText();

        if(username.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter User Name!!!");
        }
        else if(password.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Password!!!");
        }
        else if(conf_password.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Confirm Password!!!");
        }
        else if(!password.equals(conf_password))
        {
            JOptionPane.showMessageDialog(null, "Password And Confirm Password Does Not Match!!! \n Please Try Again");
        }

        else
        {
            System.out.println("User Name :"+username);
            System.out.println("Password :"+password);
            System.out.println("Confirm Password :"+conf_password);
            AdminDBOperation cdop=new AdminDBOperation();
            if(cdop.isProfileUpdate( username,password))
            {
                JOptionPane.showMessageDialog(null, "Profile Updated Successfully");

                jTextField5.setText(null);
                jPasswordField1.setText(null);
                jPasswordField2.setText(null);

            }
            else
            {
                JOptionPane.showMessageDialog(null, "Oops !! Error Occured During Data Updating");
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

