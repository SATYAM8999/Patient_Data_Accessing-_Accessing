    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String clientname = (String) jComboBox1.getSelectedItem();
        String tablename = (String) jComboBox2.getSelectedItem();
        tablename = tablename.substring(0, tablename.lastIndexOf("."));
        tde = new TamperDetectionEngine();
        tde.clientname = clientname;
        tde.tablename=tablename;
        tde.flag=true;
        tde.start();
        DBTemperDetectionFrame.jTextArea1.append("DB Engine Started.... \n");
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jComboBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1ActionPerformed
        // TODO add your handling code here:
        String clientname = (String) jComboBox1.getSelectedItem();
        ArrayList table_name = new ArrayList();
        for (int i = 0; i < client_data.size(); i++) 
        {
            ArrayList row = (ArrayList) client_data.get(i);
            String cn = (String) row.get(0);
            String tablename = (String) row.get(1);
            if (clientname.equals(cn)) 
            {
                table_name.add(tablename);
            }
        }
        String tn[] = new String[table_name.size()];
        for (int i = 0; i < table_name.size(); i++)
        {
            String temp = (String) table_name.get(i);
            tn[i] = temp;
        }
        DefaultComboBoxModel dcb = new DefaultComboBoxModel(tn);
        jComboBox2.setModel(dcb);
    }//GEN-LAST:event_jComboBox1ActionPerformed

