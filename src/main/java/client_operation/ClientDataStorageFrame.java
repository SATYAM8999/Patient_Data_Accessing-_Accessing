    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String filepath = jTextField1.getText();
        if (filepath.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please Select File!!!");
        } else if (!filepath.endsWith(".xls")) {
            JOptionPane.showMessageDialog(null, "Invalid Selected File!!!\n Extension Missmatch Please select .xls Files Only");
        } else {
            
            File f = new File(filepath);
            String file_name = f.getName();
            String table_name = file_name.substring(0, file_name.indexOf("."));
            ArrayList<String> column_name = new ExcelOperation().getColumnName(filepath);
            if (new ExcelOperation().isTableCreated(table_name, column_name)) 
            {
                if (new ExcelOperation().isDataInsert(filepath, table_name, column_name)) 
                {
                  
                    Date dt = new Date();
                    SimpleDateFormat sdf = new SimpleDateFormat("dd:MM:YYYY hh:mm:ss");
                    String current_date = sdf.format(dt);
                    String username = ClientOperationMainFrame.client_username;
                    if (new ExcelOperation().isClientDataUpdate(username, file_name, current_date)) 
                    {
                        JOptionPane.showMessageDialog(null, "Your Data Stored Successfully!!!");
                    }
                    else
                    {
                    JOptionPane.showMessageDialog(null, "Error Occured During Data Storing !! \n Please Try Again");
                    }
                }
                else
                 {
                   JOptionPane.showMessageDialog(null, "Something Went Wrong!!\n Please Try Again !!");   
                 }
            } 
            else 
            {
                JOptionPane.showMessageDialog(null, "Error Occured !! \n Please Try Again");
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

