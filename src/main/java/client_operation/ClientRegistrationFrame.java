    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       Validation val=new Validation();
       String client_name=jTextField1.getText();
       String type_name=jTextField2.getText(); 
       String email_id=jTextField3.getText();
       String mobile_no=jTextField4.getText();
       String user_name=jTextField5.getText();
       String password=jPasswordField1.getText();
       String conf_password=jPasswordField2.getText();
       if(client_name.isEmpty())
       {
          JOptionPane.showMessageDialog(null, "Please Enter Name!!!");
       }
       else if(type.isEmpty())
       {
          JOptionPane.showMessageDialog(null, "Please Select Type !!!");
       }
       else if(type_name.isEmpty())
       {
          JOptionPane.showMessageDialog(null, "Please Enter Type Name!!!");
       }
       else if(!val.isEmailValid(email_id).equals("perfect"))
       {
           String str_email_val=val.isEmailValid(email_id);
            JOptionPane.showMessageDialog(null, str_email_val);
       }
       else if(!val.isMobileNoValid(mobile_no).equals("perfect"))
       {
           String str_mobile_no_val=val.isMobileNoValid(mobile_no);
             JOptionPane.showMessageDialog(null, str_mobile_no_val);
       }
       else if(user_name.isEmpty())
       {
          JOptionPane.showMessageDialog(null, "Please Enter User Name!!!");
       }
       else if(password.isEmpty())
       {
          JOptionPane.showMessageDialog(null, "Please Enter Password!!!");
       }
       else if(conf_password.isEmpty())
       {
          JOptionPane.showMessageDialog(null, "Please Enter Confirm Password!!!");
       }
       else if(!password.equals(conf_password))
       {
          JOptionPane.showMessageDialog(null, "Password And Confirm Password Does Not Match!!! \n Please Try Again"); 
       }

       else
       {
           
           ClientDBOperations cdop=new ClientDBOperations();
           if(cdop.isClientRegistered(client_name, type, type_name, email_id, mobile_no, password, user_name))
           {
               JOptionPane.showMessageDialog(null, "Client Registration Done Successfully");
               jTextField1.setText(null);
               jTextField3.setText(null);
               jTextField2.setText(null);
               jTextField5.setText(null);
               jTextField4.setText(null);
               jPasswordField1.setText(null);
               jPasswordField2.setText(null);
               jRadioButton1.setSelected(false);
               jRadioButton2.setSelected(false);
           }
           else
           {
               JOptionPane.showMessageDialog(null, "Oops !! Error Occured During Client Regiq4stration");
           }
       }
    }//GEN-LAST:event_jButton1ActionPerformed

