    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String user_name=jTextField1.getText();
        String password=jPasswordField1.getText();
        if(user_name.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Username!!!");
        }
        else if(password.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Please Enter Password!!!");
        }
        else
        {
            ClientDBOperations cdop=new ClientDBOperations();
            if(cdop.isClientExisted(user_name, password))
            {
                this.dispose();
                ClientOperationMainFrame.client_username=user_name;
                ClientOperationMainFrame comf=new ClientOperationMainFrame();
                comf.setVisible(true);
                Dimension d = Toolkit.getDefaultToolkit().getScreenSize();
                comf.setSize(d);
                
            }
            else
            {
                 JOptionPane.showMessageDialog(null, "Invalid Credential \n Please Try Again!!!");
            }
            jTextField1.setText(null);
                jPasswordField1.setText(null);
                jCheckBox1.setText(null);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

