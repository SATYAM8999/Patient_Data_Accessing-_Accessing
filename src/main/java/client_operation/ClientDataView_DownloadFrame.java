    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String file_name=(String)jComboBox1.getSelectedItem();
        String table_name = file_name.substring(0, file_name.indexOf("."));
        
        if(table_name.equals("No File Uploaded"))
        {
            JOptionPane.showMessageDialog(null, "No Data Found To Download!!!");
        }
        else
        { 
             String downloadpath=System.getProperty("user.home")+File.separator+"Downloads"+File.separator+table_name+".xls";
                   
            String column_name[]=new DataView_Download().getColumnNames(table_name);
            String tabledata[][]=new DataView_Download().getTableData(table_name, column_name.length);
              
            ArrayList attributes=new ArrayList();
            ArrayList download_data=new ArrayList();
            
            for (int i = 0; i <column_name.length; i++)
            attributes.add(column_name[i]);
            download_data.add(attributes);
            
            for (int i = 0; i <tabledata.length; i++) 
            {
                ArrayList singlerow=new ArrayList();
                for (int j = 0; j <tabledata[0].length; j++) 
                {
                    singlerow.add(tabledata[i][j]);
                }
                download_data.add(singlerow);
            }
                if(new ExcelOperation().isFileDownloaded(download_data, downloadpath))
                JOptionPane.showMessageDialog(null, "File "+table_name+"  is Downloaded Sucessfully...!\n Please Check The Floder");
            else
                JOptionPane.showMessageDialog(null, "Error in downloading...! \n Please Try Again" );

        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

